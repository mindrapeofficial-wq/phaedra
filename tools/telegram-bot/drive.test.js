import test from "node:test";
import assert from "node:assert/strict";
import { archiveCover } from "./drive.js";

test("Drive is optional; configured uploads preserve original generated bytes in a client folder", async () => {
  const keys = ["GOOGLE_CLIENT_ID", "GOOGLE_CLIENT_SECRET", "GOOGLE_REFRESH_TOKEN"];
  const saved = keys.map(key => process.env[key]);
  const originalFetch = globalThis.fetch;
  try {
    keys.forEach(key => delete process.env[key]);
    assert.equal(await archiveCover(42, ""), null);
    keys.forEach(key => process.env[key] = "test-value");
    const bytes = Buffer.from("generated-png-bytes");
    const requests = [];
    globalThis.fetch = async (url, options) => {
      requests.push(url);
      assert.ok(options.signal);
      if (url === "https://oauth2.googleapis.com/token") return Response.json({ access_token: "test-token" });
      if (url.includes("/drive/v3/files?q=")) return Response.json({ files: [] });
      if (url.endsWith("files?fields=id")) {
        assert.equal(JSON.parse(options.body).name, "Cliente 42");
        return Response.json({ id: "client-folder" });
      }
      if (url.includes("uploadType=resumable")) {
        assert.deepEqual(JSON.parse(options.body).parents, ["client-folder"]);
        return new Response(null, { headers: { location: "https://www.googleapis.com/upload/drive/session" } });
      }
      if (url.endsWith("/drive/session")) {
        assert.equal(options.method, "PUT");
        assert.deepEqual(options.body, bytes);
        return Response.json({ id: "output-file", webViewLink: "https://drive.google.com/file/d/output-file/view" });
      }
      throw new Error("Unexpected request");
    };
    assert.equal((await archiveCover(42, bytes.toString("base64"))).id, "output-file");
    assert.equal(requests.length, 5);
    assert.ok(requests.every(url => !url.includes("permissions")), "archiving must not change sharing");
  } finally {
    globalThis.fetch = originalFetch;
    keys.forEach((key, i) => saved[i] === undefined ? delete process.env[key] : process.env[key] = saved[i]);
  }
});
